-- ── 5. Nouvelle issue et groupes historiques ────────────────────────────────
-- Une issue `new` naît avec sa notification, dans la même transaction. `origin =
-- 'migration'` (clé v2 recouvrant un groupe déjà vu) ne notifie pas : c'est ce qui
-- évite de renotifier les groupes connus au basculement. Deux lots concurrents
-- ne créent qu'une issue (unicité v72), donc qu'une notification ; la clé
-- d'événement en est la seconde garantie. Security definer : le déclencheur
-- écrit l'outbox quel que soit le rôle de l'écrivain de l'issue.
create or replace function error_issue_notify_new_v73() returns trigger
language plpgsql security definer set search_path = public, pg_temp as $$
begin
  insert into error_issue_notification (app_id, issue_id, kind, event_key, payload)
  values (
    new.app_id, new.id, 'new', 'new:' || new.id,
    jsonb_build_object(
      'source', 'mip-rum', 'kind', 'new', 'app_id', new.app_id, 'issue_id', new.id,
      'first_release', new.first_release, 'severity', 'warning',
      'text', format('[MIP RUM] Nouvelle issue dans %s%s — /errors/issues/%s?app=%s',
                     new.app_id, coalesce(', release ' || new.first_release, ''), new.id, new.app_id))
  )
  on conflict (event_key) do nothing;
  return null;
end $$;

drop trigger if exists error_issue_notify_new_v73 on error_issue;
create trigger error_issue_notify_new_v73
  after insert on error_issue
  for each row when (new.origin = 'new')
  execute function error_issue_notify_new_v73();

-- Supprimer une issue (rétention, effacement d'app) emporte ses notifications par
-- cascade ; leurs événements d'alerte sans règle ne sont rattachés à rien d'autre
-- et partent avec elles. Ceux d'une règle issue:<uuid> restent à la règle.
create or replace function error_issue_notification_forget_v73() returns trigger
language plpgsql security definer set search_path = public, pg_temp as $$
begin
  delete from alert_event e
   using anciennes a
   where e.id = a.alert_event_id and e.rule_id is null and e.slo_id is null;
  return null;
end $$;

drop trigger if exists error_issue_notification_forget_v73 on error_issue_notification;
create trigger error_issue_notification_forget_v73
  after delete on error_issue_notification
  referencing old table as anciennes
  for each statement
  execute function error_issue_notification_forget_v73();

-- Reprise intégrale de migration-v64 ; seule différence : une ligne rattachée à
-- une issue est notifiée par l'outbox, jamais par ce watermark.
create or replace function check_new_errors() returns integer
  language plpgsql security definer set search_path to 'public', 'pg_temp'
as $function$
declare
  cursor_row record;
  upper_bound record;
  a record;
  fired int := 0;
  ev_id bigint;
  msg text;
  stable text;
begin
  select last_ingested_at, last_error_id
    into cursor_row
    from rum_new_error_watermark
   where singleton = true
   for update;

  select e.ingested_at, e.id into upper_bound
    from rum_error e
   where (e.ingested_at, e.id) > (cursor_row.last_ingested_at, cursor_row.last_error_id)
   order by e.ingested_at desc, e.id desc
   limit 1;

  if not found then
    return 0;
  end if;

  for a in
    select e.app_id, e.fingerprint,
           max(e.error_type) as error_type,
           max(e.message) as sample,
           min(e.ts) as first_seen,
           coalesce(sum(e.occurrences), 0)::bigint as occurrences
      from rum_error e
     where e.fingerprint is not null
       and e.issue_id is null
       and (e.ingested_at, e.id) > (cursor_row.last_ingested_at, cursor_row.last_error_id)
       and (e.ingested_at, e.id) <= (upper_bound.ingested_at, upper_bound.id)
       and not exists (
         select 1
           from rum_error seen
          where seen.app_id = e.app_id
            and seen.fingerprint = e.fingerprint
            and (seen.ingested_at, seen.id) <= (cursor_row.last_ingested_at, cursor_row.last_error_id)
       )
     group by e.app_id, e.fingerprint
  loop
    stable := format('nouvelle erreur %s / app %s', a.fingerprint, a.app_id);
    msg := format('%s — %s « %s » (%s occurrence(s) depuis %s)',
      stable, coalesce(a.error_type, 'Error'), left(coalesce(a.sample, ''), 120), a.occurrences,
      to_char(a.first_seen, 'HH24:MI'));

    if not exists (
      select 1 from alert_event ae
       where ae.rule_id is null and ae.slo_id is null
         and ae.message like '%' || stable || '%'
         and ae.fired_at > now() - interval '24 hours'
    ) then
      insert into alert_event (rule_id, slo_id, value, message, severity)
      values (null, null, a.occurrences, msg, 'warning')
      returning id into ev_id;
      fired := fired + 1;
      perform route_alert(ev_id, a.app_id, 'warning', '[MIP RUM] ' || msg,
        jsonb_build_object('source', 'mip-rum', 'kind', 'new_error', 'app_id', a.app_id,
          'fingerprint', a.fingerprint, 'error_type', a.error_type,
          'occurrences', a.occurrences, 'text', msg));
    end if;
  end loop;

  update rum_new_error_watermark
     set last_ingested_at = upper_bound.ingested_at,
         last_error_id = upper_bound.id
   where singleton = true;
  return fired;
end $function$;

-- ── 6. Régression, dans la transaction de l'écrivain ────────────────────────
-- Appelée par l'écrivain des occurrences, APRÈS leur insertion et AVANT son
-- commit, une issue à la fois dans l'ordre des identifiants (même ordre que la
-- mise à jour de première et dernière vue, donc aucun interblocage entre lots).
-- Ne reçoit que les lignes effectivement insérées : un rejeu n'en fournit aucune.
--
-- Le verrou de ligne sérialise deux écrivains concurrents : le second relit
-- l'issue après le commit du premier, la trouve rouverte et n'écrit rien. Un
-- écrivain qui a commencé tôt et valide tard décide sur l'état validé au moment
-- où il écrit, pas sur un curseur déjà dépassé.
--
-- Régression CONFIRMÉE : issue résolue, occurrence postérieure à la résolution,
-- dans l'env de référence, sur une release dont le premier marqueur de
-- déploiement de cet env est strictement postérieur à celui de la release de
-- référence. Jamais d'ordre lexical ni SemVer : une release sans marqueur, la
-- même release, une plus ancienne ou un env inconnu rendent `reappearance` —
-- « réapparition à vérifier », sans rouvrir. Une issue ignorée, ouverte ou à
-- revoir n'est pas touchée.
create or replace function error_issue_record_occurrences(
  p_app_id text, p_issue_id uuid, p_ts timestamptz[], p_releases text[], p_envs text[]
) returns text
language plpgsql as $$
declare
  i record;
  confirmee record;
  cle text;
begin
  select id, status, resolved_at, resolved_release, resolved_env
    into i
    from error_issue
   where app_id = p_app_id and id = p_issue_id
   for update;
  if not found or i.status <> 'resolved' or i.resolved_at is null then
    return null;
  end if;
  if not exists (select 1 from unnest(p_ts) as t (ts) where t.ts > i.resolved_at) then
    return null;
  end if;

  select o.release, o.ts
    into confirmee
    from unnest(p_ts, p_releases, p_envs) as o (ts, release, env)
    cross join lateral (
      select min(m.ts) as deployed_at
        from deploy_marker m
       where m.app_id = p_app_id and m.env = i.resolved_env and m.version = o.release
    ) occ
   where o.ts > i.resolved_at
     and o.env = i.resolved_env
     and occ.deployed_at > (
       select min(m.ts) from deploy_marker m
        where m.app_id = p_app_id and m.env = i.resolved_env and m.version = i.resolved_release
     )
   order by occ.deployed_at desc, o.ts
   limit 1;
  if not found then
    return 'reappearance';
  end if;

  cle := 'regression:' || (extract(epoch from i.resolved_at) * 1000000)::bigint;
  update error_issue
     set status = 'open', status_source = 'system',
         resolved_at = null, resolved_by_user_id = null, resolved_release = null, resolved_env = null,
         revision = revision + 1, updated_at = now()
   where app_id = p_app_id and id = p_issue_id;
  insert into error_issue_activity
    (app_id, issue_id, kind, actor_kind, old_status, new_status, release, reference_release, env, event_key)
  values
    (p_app_id, p_issue_id, 'regression', 'system', 'resolved', 'open',
     confirmee.release, i.resolved_release, i.resolved_env, cle)
  on conflict (app_id, issue_id, event_key) where event_key is not null do nothing;
  insert into error_issue_notification (app_id, issue_id, kind, event_key, payload)
  values (
    p_app_id, p_issue_id, 'regression', cle || ':' || p_issue_id,
    jsonb_build_object(
      'source', 'mip-rum', 'kind', 'regression', 'app_id', p_app_id, 'issue_id', p_issue_id,
      'release', confirmee.release, 'reference_release', i.resolved_release, 'env', i.resolved_env,
      'severity', 'warning',
      'text', format('[MIP RUM] Régression confirmée dans %s : release %s déployée après %s (env %s) — /errors/issues/%s?app=%s',
                     p_app_id, confirmee.release, i.resolved_release, i.resolved_env, p_issue_id, p_app_id))
  )
  on conflict (event_key) do nothing;
  return 'regression';
end $$;

comment on function error_issue_record_occurrences(text, uuid, timestamptz[], text[], text[]) is
  'Régression confirmée (rouvre, activité, outbox) ou réapparition à vérifier, décidée dans la transaction de l''écrivain';

-- ── 7. Routage de l'outbox ──────────────────────────────────────────────────
-- Étape du tick existant, déclenché par le scheduler ET par le cron GitHub : deux
-- passes simultanées prennent des lignes disjointes (`skip locked`), et une ligne
-- n'est routée qu'une fois (état relu sous verrou). Tout se passe dans la
-- transaction de l'appel : un échec de route_alert annule son alert_event et
-- programme une nouvelle tentative (30 s × 2^tentatives, 5 au plus).
create or replace function route_error_issue_notifications(p_limit integer default 100) returns integer
language plpgsql security definer set search_path = public, pg_temp as $$
declare
  n record;
  ev_id bigint;
  webhook text;
  routees int := 0;
begin
  for n in
    select *
      from error_issue_notification
     where state = 'pending' and next_attempt_at <= now()
     order by next_attempt_at, id
     limit greatest(p_limit, 1)
     for update skip locked
  loop
    begin
      insert into alert_event (rule_id, value, message, severity)
      values (n.rule_id, (n.payload->>'value')::double precision,
              regexp_replace(n.payload->>'text', '^\[MIP RUM\] ', ''), n.payload->>'severity')
      returning id into ev_id;
      if n.rule_id is not null then
        select webhook_url into webhook from alert_rule where id = n.rule_id;
        if webhook is not null then
          insert into alert_delivery (alert_event_id, target) values (ev_id, webhook);
        end if;
      end if;
      perform route_alert(ev_id, n.app_id, n.payload->>'severity', n.payload->>'text', n.payload);
      update error_issue_notification
         set state = 'delivered', alert_event_id = ev_id, attempts = attempts + 1,
             delivered_at = now(), last_error = null
       where id = n.id;
      routees := routees + 1;
    exception when others then
      update error_issue_notification
         set attempts = attempts + 1,
             last_error = left(sqlerrm, 500),
             state = case when attempts + 1 >= 5 then 'failed' else 'pending' end,
             next_attempt_at = now() + interval '30 seconds' * power(2, attempts)
       where id = n.id;
    end;
  end loop;
  return routees;
end $$;

comment on function route_error_issue_notifications(integer) is
  'Remet les notifications d''issue en attente à route_alert (alert_event + livraisons), une seule fois chacune';

