-- Un événement d'alerte né d'une notification d'issue sans règle appartient à
-- l'app de l'issue : même portée que ceux d'une règle ou d'un SLO.
drop policy if exists tenant_scope on alert_event;
create policy tenant_scope on alert_event for all to console_ro using (
  exists (select 1 from alert_rule r where r.id = alert_event.rule_id
            and r.app_id = any (current_app_ids()))
  or
  exists (select 1 from slo s where s.id = alert_event.slo_id
            and s.app_id = any (current_app_ids()))
  or
  exists (select 1 from error_issue_notification n where n.alert_event_id = alert_event.id
            and n.app_id = any (current_app_ids()))
);

