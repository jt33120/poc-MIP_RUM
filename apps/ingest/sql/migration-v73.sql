-- migration-v73 — P5.6 : triage, régressions et notifications par issue.
--
-- Additive et rejouable, PostgreSQL 15 à 17. S'applique APRÈS migration-v72
-- (error_issue) et refuse de s'appliquer sans elle.
--
--   1. error_issue_ticket : liens de ticket saisis à la main (HTTPS, 2 048
--      caractères, libellé de 120). Aucune synchronisation fournisseur (P8.6).
--   2. error_issue_activity : historique append-only — statut, assignation,
--      commentaire, lien, régression. Jamais de stack, de message d'erreur ni
--      d'identité RUM : seuls des identifiants internes, des releases et du texte
--      saisi par un opérateur, déjà scrubbé par l'écrivain.
--   3. error_issue_notification : outbox des notifications d'issue (nouvelle,
--      régression, pic), une clé d'événement unique par notification, remise au
--      routage existant (route_alert) par route_error_issue_notifications().
--   4. RLS et droits. Les trois tables suivent leur issue par clé étrangère en
--      cascade : purge_rum_app et erase_app_data (v71/v72) ne sont PAS
--      redéfinies, la rétention et l'effacement d'une issue emportent son
--      historique, ses liens et ses notifications.
--   5. Nouvelle issue : l'outbox est écrite par déclencheur, dans la transaction
--      qui crée l'issue. check_new_errors (v64) garde son watermark pour les
--      groupes historiques et ignore désormais les lignes rattachées à une issue.
--   6. Régression : error_issue_record_occurrences(), appelée par l'écrivain dans
--      SA transaction, issue verrouillée — jamais un curseur relu après coup.
--   7. Alertes issue:<uuid> : fenêtre et baseline exactes, no_data explicite,
--      pic remis à l'outbox sous une clé d'événement.
--   8. Livraison : les livraisons sans règle restées en file sont soldées
--      (skipped) avant que le dispatcher local ne les prenne en charge.
--
-- POURQUOI PAS UN CURSEUR. check_new_errors avance un watermark (ingested_at, id) :
-- une transaction qui alloue ses identifiants tôt et valide tard reste derrière
-- le curseur et n'est jamais relue. Ici, la décision est prise dans la
-- transaction qui écrit (régression) ou par déclencheur sur la ligne créée
-- (nouvelle issue), et l'outbox est dépilée par état, pas par identifiant.
--
-- FENÊTRE DE DÉPLOIEMENT. Le code P5.6 publié avant ce fichier détecte l'absence
-- des tables : la console répond 503 aux mutations de triage, le dispatcher et
-- les travaux planifiés gardent leur comportement antérieur.
--
-- VERROUS. Aucune table chaude n'est modifiée : error_issue, alert_rule,
-- alert_event et alert_config sont petites. `lock_timeout` borne chaque attente ;
-- s'il expire, le fichier entier est annulé et le déploiement rejoué.
set local lock_timeout = '5s';

do $$
begin
  if to_regclass('public.error_issue') is null then
    raise exception 'v73 : migration-v72 (error_issue) doit être appliquée avant ce fichier';
  end if;
end $$;

-- ── 1. Liens de ticket ──────────────────────────────────────────────────────
-- ASCII imprimable seulement : l'URL est normalisée par l'écrivain (points de
-- code hors ASCII encodés), et la borne en caractères devient une borne en
-- octets, compatible avec l'index d'unicité.
create table if not exists error_issue_ticket (
  id                  bigint generated by default as identity primary key,
  app_id              text not null,
  issue_id            uuid not null,
  url                 text not null,
  label               text not null,
  created_by_user_id  bigint references console_user (id) on delete set null,
  created_at          timestamptz not null default now(),
  constraint error_issue_ticket_issue_v73 foreign key (app_id, issue_id)
    references error_issue (app_id, id) on delete cascade,
  constraint error_issue_ticket_ref_v73 unique (app_id, issue_id, id),
  constraint error_issue_ticket_url_v73 unique (app_id, issue_id, url),
  constraint error_issue_ticket_v73 check (
    char_length(url) between 9 and 2048 and url ~ '^https://[!-~]+$' and
    char_length(label) between 1 and 120 and label !~ '[[:cntrl:]]'
  )
);

comment on table error_issue_ticket is
  'Liens de ticket attachés à la main à une issue (P5.6) ; aucune donnée n''est envoyée au fournisseur';

-- ── 2. Activité ─────────────────────────────────────────────────────────────
-- Les colonnes utilisateur sont des clés vers console_user, jamais un email. Un
-- compte supprimé laisse NULL : aucune contrainte ne lie donc l'acteur, l'ancien
