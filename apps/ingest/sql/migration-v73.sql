-- `env` n'a de sens que pour une issue (rum_error.env) : il est refusé ailleurs
-- plutôt qu'ignoré en silence. `last_*` rend visible chaque évaluation, dont
-- no_data, que check_alerts traitait jusqu'ici comme une absence d'alerte.
alter table alert_rule
