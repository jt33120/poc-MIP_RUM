-- Depuis quand l'issue est-elle observable ? L'activation v2 en cours de son app :
-- avant elle, aucune occurrence n'est rattachée à une issue et un zéro ne prouve
-- rien. NULL : issue absente de l'app, ou regroupement v2 inactif.
create or replace function issue_metric_observable_since(p_app_id text, p_issue_id uuid) returns timestamptz
language sql stable set search_path = public, pg_temp as $$
  select c.activated_at
    from error_grouping_config c
    join error_issue i on i.app_id = c.app_id and i.id = p_issue_id
   where c.app_id = p_app_id and c.active_version = 2
$$;

-- Occurrences observées d'une issue sur (p_from, p_to] : sommes des répétitions,
-- bots exclus, route et env de la règle, session jointe dans l'app. Les mêmes
-- prédicats servent la fenêtre courante et chaque fenêtre de la baseline. La
-- probabilité d'inclusion minimale (sr + (1 − sr) × esr) signale l'échantillon.
create or replace function issue_metric_window(
  p_app_id text, p_issue_id uuid, p_route text, p_env text, p_from timestamptz, p_to timestamptz
) returns table (occurrences double precision, min_inclusion double precision)
language sql stable set search_path = public, pg_temp as $$
  select coalesce(sum(e.occurrences), 0)::double precision,
         min(case when s.session_id is not null
                  then coalesce(s.sample_rate, 1) + (1 - coalesce(s.sample_rate, 1)) * coalesce(s.error_sample_rate, 1)
             end)::double precision
    from rum_error e
    left join rum_session s on s.app_id = e.app_id and s.session_id = e.session_id
   where e.app_id = p_app_id and e.issue_id = p_issue_id
     and e.ts > p_from and e.ts <= p_to
     and (p_route is null or e.route = p_route)
     and (p_env is null or e.env = p_env)
     and not coalesce(s.is_bot, false)
$$;

-- Baseline exacte : la fenêtre de la règle, finissant à la même heure chacune des
-- semaines précédentes, zéros compris (P4). Seule différence : une fenêtre n'est
-- COMPARABLE que si l'issue y était entièrement observable et ses données encore
-- conservées (rétention de l'app, 30 jours par défaut comme purge_rum_tenants).
-- n compte les fenêtres comparables ; check_alerts en exige 4.
create or replace function issue_metric_baseline(
  p_app_id text, p_issue_id uuid, p_route text, p_env text, p_weeks integer, p_window_minutes integer
) returns table (med double precision, mad double precision, n integer)
language sql stable set search_path = public, pg_temp as $$
  with bornes as (
    select greatest(
             issue_metric_observable_since(p_app_id, p_issue_id),
             now() - make_interval(days => greatest(coalesce(
               (select retention_days from app_registry where app_id = p_app_id), 30), 1))
           ) as depuis
  ), anchors as (
    select now() - make_interval(weeks => g) as hi
      from generate_series(1, greatest(p_weeks, 1)) g, bornes
     where now() - make_interval(weeks => g) - make_interval(mins => greatest(p_window_minutes, 1)) >= bornes.depuis
  ), samples as (
    select w.occurrences as val
      from anchors a
     cross join lateral issue_metric_window(
       p_app_id, p_issue_id, p_route, p_env, a.hi - make_interval(mins => greatest(p_window_minutes, 1)), a.hi) w
  ), m as (
    select percentile_cont(0.5) within group (order by val) v from samples
  )
  select (select v from m),
         percentile_cont(0.5) within group (order by abs(val - (select v from m))),
         count(*)::int
    from samples
$$;

do $$
