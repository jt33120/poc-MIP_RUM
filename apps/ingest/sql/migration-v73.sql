  app_id                text not null,
  issue_id              uuid not null,
  kind                  text not null,
  actor_kind            text not null,
  actor_user_id         bigint references console_user (id) on delete set null,
  old_status            text,
  new_status            text,
  old_assignee_user_id  bigint references console_user (id) on delete set null,
  new_assignee_user_id  bigint references console_user (id) on delete set null,
  body                  text,
  legacy_fingerprint    text,
  ticket_id             bigint,
  release               text,
  reference_release     text,
  env                   text,
  event_key             text,
  created_at            timestamptz not null default now(),
  constraint error_issue_activity_issue_v73 foreign key (app_id, issue_id)
    references error_issue (app_id, id) on delete cascade,
  constraint error_issue_activity_ticket_v73 foreign key (app_id, issue_id, ticket_id)
    references error_issue_ticket (app_id, issue_id, id) on delete cascade,
  constraint error_issue_activity_v73 check (
    kind in ('status', 'assignee', 'comment', 'link', 'regression') and
    actor_kind in ('user', 'system') and
    (actor_kind = 'user' or actor_user_id is null) and
    (old_status is null or old_status in ('open', 'for_review', 'resolved', 'ignored')) and
    (new_status is null or new_status in ('open', 'for_review', 'resolved', 'ignored')) and
    (kind not in ('status', 'regression') or (old_status is not null and new_status is not null
                                              and old_status <> new_status)) and
    (kind in ('status', 'regression') or (old_status is null and new_status is null)) and
    (kind <> 'status' or actor_kind = 'user') and
    (kind <> 'regression' or (actor_kind = 'system' and old_status = 'resolved' and new_status = 'open'
                              and release is not null and reference_release is not null and env is not null)) and
    (kind <> 'assignee' or actor_kind = 'user') and
    ((kind = 'comment') = (body is not null)) and
    (body is null or char_length(body) between 1 and 2000) and
    (kind <> 'comment' or actor_kind = 'user' or legacy_fingerprint is not null) and
    (legacy_fingerprint is null or (kind = 'comment' and actor_kind = 'system'
                                    and char_length(legacy_fingerprint) between 1 and 64)) and
    ((kind = 'link') = (ticket_id is not null)) and
    (kind in ('status', 'regression') or (release is null and reference_release is null and env is null)) and
    (release is null or char_length(release) between 1 and 200) and
    (reference_release is null or char_length(reference_release) between 1 and 200) and
    (env is null or char_length(env) between 1 and 120) and
    (event_key is null or char_length(event_key) between 1 and 200)
  )
);

